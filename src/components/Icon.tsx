export type IconName = keyof typeof icons

interface Props {
  name: IconName
  size?: number
  filled?: boolean
  strokeWidth?: number
}

export function Icon({ name, size = 20, filled = false, strokeWidth = 2 }: Props) {
  const Cmp = icons[name]
  return <Cmp size={size} strokeWidth={strokeWidth} fill={filled ? 'currentColor' : 'none'} aria-hidden="true" />
}
